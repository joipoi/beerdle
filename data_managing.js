// Turns the output of the systembolaget-api tool into beer_data.js.
// Usage: node data_managing.js [input file] (defaults to systembolaget_list.json)
const fs = require('fs');

const INPUT_FILE = process.argv[2] || 'systembolaget_list.json';
const OUTPUT_FILE = 'beer_data.js';

// The tool writes one JSON object per line. This also accepts a normal JSON array,
// or one object per line wrapped in [ ] with trailing commas.
function read_systembolaget_file(path) {
  const text = fs.readFileSync(path, 'utf-8').trim();
  try {
    return JSON.parse(text);
  } catch {
    return text
      .split('\n')
      .map(line => line.trim().replace(/,$/, ''))
      .filter(line => line.startsWith('{'))
      .map(line => JSON.parse(line));
  }
}

// Systembolaget uses 0 both for "not rated" and for a real 0, so a clock only
// counts when the beer actually has a tasteClocks list.
function get_taste_clock(sBeer, value) {
  return sBeer.tasteClocks && sBeer.tasteClocks.length ? value : null;
}

function to_beer(sBeer) {
  return {
    "productId": sBeer.productId,
    "productNameBold": sBeer.productNameBold,
    "productNameThin": sBeer.productNameThin,
    "producerName": sBeer.producerName,
    "alcoholPercentage": sBeer.alcoholPercentage,
    "categoryLevel2": sBeer.categoryLevel2,
    "categoryLevel3": sBeer.categoryLevel3,
    "price": sBeer.price,
    "volume": sBeer.volume,
    "packaging": sBeer.bottleText,
    "country": sBeer.country,
    "assortment": sBeer.assortmentText,
    "hasImage": Boolean(sBeer.images && sBeer.images.length),
    "bitterness": get_taste_clock(sBeer, sBeer.tasteClockBitter),
    "body": get_taste_clock(sBeer, sBeer.tasteClockBody),
    "sweetness": get_taste_clock(sBeer, sBeer.tasteClockSweetness),
    "fruitAcid": get_taste_clock(sBeer, sBeer.tasteClockFruitacid),
    "color": sBeer.color,
    "taste": sBeer.taste,
    "usage": sBeer.usage
  };
}

function get_beer_name(beer) {
  return [beer.productNameBold, beer.productNameThin].filter(Boolean).join(' ').toLowerCase();
}

// Higher score = better entry to keep when the same beer is sold in several packagings.
function score_beer(beer) {
  return (beer.hasImage ? 2 : 0) +
    (beer.taste ? 2 : 0) +
    (beer.assortment === 'Fast sortiment' ? 1 : 0);
}

// The same beer often exists as both can and bottle with different product ids.
// Keep one entry per name so the search list has no duplicates.
function remove_duplicates(beers) {
  const byName = new Map();

  for (const beer of beers) {
    const name = get_beer_name(beer);
    const existing = byName.get(name);

    if (!existing) {
      byName.set(name, beer);
    } else {
      const keep = score_beer(beer) > score_beer(existing) ? beer : existing;
      const drop = keep === beer ? existing : beer;
      console.log(`Duplicate "${name}": keeping ${keep.productId}, dropping ${drop.productId}`);
      byName.set(name, keep);
    }
  }

  return [...byName.values()];
}

function prepare_data() {
  const systembolaget_list = read_systembolaget_file(INPUT_FILE);

  const beers = remove_duplicates(
    systembolaget_list
      .filter(sBeer => sBeer.categoryLevel1 === 'Öl' && !sBeer.isDiscontinued)
      .map(to_beer)
  );

  beers.sort((a, b) => get_beer_name(a).localeCompare(get_beer_name(b), 'sv'));

  const lines = beers.map(beer => '  ' + JSON.stringify(beer));
  const output =
    '// Generated by data_managing.js. This is the full list of beers that can be guessed.\n' +
    'const beers = [\n' + lines.join(',\n') + '\n];\n';

  fs.writeFileSync(OUTPUT_FILE, output);
  console.log(`Wrote ${beers.length} beers (from ${systembolaget_list.length}) to ${OUTPUT_FILE}`);
}

prepare_data();
